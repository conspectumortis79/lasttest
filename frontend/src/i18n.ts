// Plurals / interpolated values that need a function. The shape
// `Record<SupportedLanguage, T>` keeps the lookup symmetric.
export const formatters = {
  // Counter for the doc popup search.
  docPopupCounter: {
    en: (hits: number) => hits === 0 ? '0 matches' : hits === 1 ? '1 match' : `${hits} matches`,
    de: (hits: number) => hits === 0 ? '0 Treffer' : hits === 1 ? '1 Treffer' : `${hits} Treffer`,
  } satisfies Record<SupportedLanguage, (hits: number) => string>,
}

export type DictKey = keyof (typeof dict)['en']

/**
 * Resolves a key in the active language dict with optional
 * placeholder substitution. Tokens of the form `{name}` are
 * replaced by the matching entry in `vars`. Unknown placeholders
 * are left in place so the author can spot the typo. Falls back
 * to the English entry, then to the German one, finally to the
 * key itself — so the UI never blanks out during development.
 */
export function translate(lang: SupportedLanguage, key: DictKey, vars?: Record<string, string | number>): string {
  let template = dict[lang][key]
  if (template === undefined) template = dict.en[key] ?? dict.de[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name]
    return value === undefined ? match : String(value)
  })
}
